function CoinPixel({ coin, size = 3 }) {
  const grid = COIN_ICONS[coin];
  if (!grid) return null;
  const c = COIN_COLORS[coin];
  return (
    <PixelGrid
      grid={grid}
      colors={{ 0: "transparent", 1: c }}
      pixelSize={size}
    />
  );
}


